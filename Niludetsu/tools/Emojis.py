class Emojis:
    @staticmethod
    def combine(*emojis: Union[str, 'Emojis']) -> str:
        """
        Объединяет несколько эмодзи в одну строку

        Пример:
        >>> Emojis.combine(Emojis.SUCCESS, Emojis.ERROR, "<:custom:123456>")
        "✅❌<:custom:123456>"
        """
        return ''.join(str(emoji) for emoji in emojis) 

