def _(guild_id=None, ctx=None, bot=None):
    if ctx is not None:
        gid = ctx.guild.id if ctx.guild else 0
        b = ctx.bot if hasattr(ctx, "bot") else bot
    elif guild_id is not None:
        gid = guild_id
        b = bot
    else:
        gid = 0
        b = None

    def t(module: str, key: str, **kwargs) -> str:
        if b is not None and hasattr(b, "config_manager"):
            return b.config_manager.get_locale_text(gid, module, key, **kwargs)
        text = DEFAULT_LOCALE.get(module, {}).get(key, "")
        if kwargs and text:
            for k, v in kwargs.items():
                text = text.replace(f"{{{k}}}", str(v))
        return text

    return t

